/**
 * Іконка до назви уроку, щоб дитина знаходила предмет оком, не вчитуючись.
 * Назви в розкладі скорочені по-різному («Укр. мова», «Україн. мова»),
 * тому шукаємо за коренем слова. Порядок важливий: «літ» перевіряємо
 * раніше за «укр», інакше українська література отримала б іконку мови.
 */
const SUBJECT_ICONS: [string, string][] = [
  ["математ", "🔢"],
  ["літ", "📖"],
  ["укр", "✏️"],
  ["англ", "🌍"],
  ["польс", "🗣️"],
  ["фізичн", "🏀"],
  ["музич", "🎵"],
  ["образотв", "🎨"],
  ["технол", "✂️"],
  ["інформат", "💻"],
  ["сеен", "🌱"],
  ["природ", "🦋"],
  ["історі", "🏰"],
  ["збд", "🛡️"],
];

export const subjectIcon = (subject: string) => {
  const name = subject.toLowerCase();
  return SUBJECT_ICONS.find(([root]) => name.includes(root))?.[1] ?? "";
};
